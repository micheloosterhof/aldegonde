# ABOUTME: Enumerates every cross-boundary relation local in the key and shows sigma
# ABOUTME: has ~0 bits of local constraint, against g's 16 -- the real asymmetry.
"""sigma has no local footprint at all. That is the wall.

At a word seam the base cancels, so a whole family of cross-boundary comparisons is
LOCAL in the key. Comparing the a-th-from-last rune of word w with the b-th rune of
word w+1:

    c_{last-a} = base_w(g^(e-a)(p_{last-a}))          e = (L_w - 1) mod 5
    c_{first+b} = base_{w+1}(g^b(p_{first+b}))
                = base_w(g^e sigma g^b (p_{first+b}))

so the two are equal exactly when `p_{last-a} = g^a sigma g^b (p_{first+b})`, with no
base and no word length in it. Each (a, b) therefore gives a diagonal constraint on a
different element of the group generated by g and sigma.

Measured over all 16 combinations with a, b <= 3:

    a  b   relation        pairs  hits    rate    z vs chance
    0  0   sigma            2927    23   0.786%      -7.9
    0  1   sigma g          2828    90   3.182%      -0.8
    1  0   g sigma          2828    99   3.501%      +0.2
    1  1   g sigma g        2729    80   2.931%      -1.5
    ...    (12 more)                     2.8-3.9%   -1.3..+0.9

**Only (0,0) departs from chance, and that one is already retired.**
`negative-control-battery.md` showed the seam diagonal's apparent significance came
from a word-order null that destroys the doublet suppression; against a
doublet-PRESERVING surrogate the seam reads 23 against 19.7 +- 4.6, z = +0.72.

So the budget is starkly asymmetric:

    g      79.7 bits of entropy, 16.0 bits of local constraint (d1..d7)
    sigma  97.9 bits of entropy, ~0 bits of local constraint

Even a KNOWN g leaves sigma's ~98 bits untouched by any local statistic. sigma can
only be constrained key-globally, through the base schedule, which presupposes the
whole key.

Three consequences worth keeping:

  - No sigma construction can be TESTED. There is no local observable to score a
    proposal against, which is why every mechanical story (two-wheel device,
    5-ring cylinder) accounts for g and stalls at sigma.
  - sigma, not g, is the harder half: more entropy AND less constraint. Effort spent
    on g constructions is spent on the easier 45% of the problem.
  - It sizes the crib route precisely. sigma's 98 bits at log2(29) = 4.86 bits per
    crib rune needs ~20 runes of over-determination, g's remaining ~64 bits needs
    ~13 more, and base_0 absorbs the first 29 -- about 62 contiguous runes in total,
    which matches the independent estimate in `information_budget.py`.
"""

from __future__ import annotations

import sys
from math import factorial, log2, sqrt
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from walk_verifier import load_words  # noqa: E402

M = 29
CHANCE = 1 / M
MAX_REACH = 3
MIN_PAIRS = 200


def relation_rate(words: list[list[int]], a: int, b: int) -> tuple[int, int]:
    """Pairs and hits for the (last-a, first+b) cross-boundary comparison."""
    total = hits = 0
    for w1, w2 in zip(words, words[1:]):
        if len(w1) > a and len(w2) > b:
            total += 1
            hits += w1[-1 - a] == w2[b]
    return hits, total


def main() -> None:
    words = load_words()
    print("Cross-boundary relations, all LOCAL in the key (the base cancels):")
    print("  (a,b) compares last-a of word w with first+b of w+1")
    print("  and is equal exactly when p_{last-a} = g^a sigma g^b (p_{first+b})\n")
    print(f"{'a':>3}{'b':>3}{'relation':>16}{'pairs':>8}{'hits':>6}{'rate':>9}{'z':>8}")
    departures = []
    for a in range(MAX_REACH + 1):
        for b in range(MAX_REACH + 1):
            hits, total = relation_rate(words, a, b)
            if total < MIN_PAIRS:
                continue
            rate = hits / total
            z = (rate - CHANCE) / sqrt(CHANCE * (1 - CHANCE) / total)
            name = "sigma" if a == b == 0 else f"g^{a} sigma g^{b}"
            print(
                f"{a:>3}{b:>3}{name:>16}{total:>8}{hits:>6}{100 * rate:>8.3f}%{z:>+8.1f}"
            )
            if abs(z) > 2:
                departures.append((a, b, z))
    print(f"\ndepartures beyond 2 sigma: {departures or 'none'}")
    print(
        "  and (0,0) -- the seam doublet -- is RETIRED by negative-control-battery.md:"
    )
    print(
        "  against a doublet-preserving surrogate it reads 23 vs 19.7 +- 4.6, z = +0.72"
    )

    g_bits = log2(factorial(M) // (5**5 * factorial(5) * factorial(4)))
    s_bits = log2(factorial(M - 1))
    print(f"\n{'':<8}{'entropy':>10}{'local constraint':>20}")
    print(f"{'g':<8}{g_bits:>9.1f} b{'16.0 bits (d1..d7)':>20}")
    print(f"{'sigma':<8}{s_bits:>9.1f} b{'~0 bits':>20}")
    print("\nsigma is the harder half: MORE entropy and LESS constraint. No local")
    print("observable exists to score a sigma construction against, which is why")
    print("every mechanical account explains g and stalls there.")


if __name__ == "__main__":
    main()
