# ABOUTME: Shows the recorded phase-gating refutation has no power, and replaces it with
# ABOUTME: a doublet-gap test that does, which disfavours the quagmire-dodge model.
"""The test that refuted phase-gating cannot see it. A gap test can, and it says no.

`period5-doublet-linkage.md` lists under "Evidence against":

    Doublets are not phase-gated. If a doublet survived only ~1 phase in 5, the 86
    doublets would pile up at one absolute position mod 5. They do not:
    {0:21, 1:16, 2:11, 3:20, 4:18}, chi2(4) = 3.65 -- flat.

**That test has no power against the mechanism it refutes.** Under `quagmire-dodge.md`
the dodge advances the clock an extra step every time it fires, so the clock drifts away
from absolute position -- about one step per 34 runes, which decorrelates the two within
a page. Simulating the model and applying its own test:

    the body                             63 doublets   chi2 = 4.06
    quagmire-dodge, 40 seeds             67 doublets   chi2 = 3.45 +- 3.09

The corpus's value is an ordinary draw from the model it was used to reject --
P(chi2 >= the body's | the dodge) = 0.30. A model built on phase-gating passes the
test that was used to reject phase-gating, so the entry establishes nothing either way.

## The statistic that does work

Phase gating constrains the **clock advance between consecutive surviving doublets** to
be zero mod 5, and the clock advance is the rune gap plus the dodges in between. For
short gaps few dodges intervene, so the rune gap itself carries the signature. It lands
on residue 4 rather than 0 because a surviving doublet advances the clock twice at its
own position.

The absolute residue depends on the key, so each corpus is rotated to put its own modal
residue first before profiles are compared. That rotation flatters concentration, and it
is applied to the corpus as well as to the models, so it works in the dodge's favour.

    aligned profile of gaps <= 40 runes
    quagmire-dodge, one zero offset     [0.62, 0.03, 0.02, 0.08, 0.26]
    probabilistic preventer             [0.36, 0.17, 0.16, 0.15, 0.16]
    the body, 12 short gaps             [0.42, 0.25, 0.17, 0.00, 0.17]

## Result

Reference profiles are built from held-out seeds, so no corpus is scored against a
profile it helped build. The classifier is checked on corpora whose generator is known:

    generated by quagmire-dodge    classified correctly 76%
    generated by the preventer     classified correctly 91%
    THE BODY                       log LR +4.27, about 71 : 1 for the preventer
                                   P(llr >= observed | dodge) = 0.000 over 80 draws

The body sits in the middle of the preventer's distribution and outside the dodge's.

**What this does and does not settle.** It bears on the dodge variant as specified --
a five-step schedule with exactly one zero offset, which `quagmire-dodge.md` requires,
since with no zero offset the model emits no doublets at all. It rests on **12 short
gaps**, which is thin, and the simulations run on prose rather than the LP's own
register. The gap signature is driven by clock mechanics rather than by plaintext, so
register should matter little, but that is an argument and not a measurement.

    python doublet_gaps_test_the_dodge.py
"""

from __future__ import annotations

import math
import random
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "experiments"))

from compact_state_models import order5, prose_corpora  # noqa: E402
from does_the_cipher_restart import body_blocks  # noqa: E402
from quagmire_dodge import M, alphabets, encipher, schedule  # noqa: E402

GAP_LIMITS = (30, 40, 60, 90)
REFERENCE_SEEDS = range(500, 620)  # held out from every corpus that gets scored
TRIALS = 80


def compose(p, q):
    return [p[q[i]] for i in range(len(p))]


def power(p, k):
    out = list(range(len(p)))
    for _ in range(k):
        out = compose(p, out)
    return out


def plaintext():
    return prose_corpora(2896, 1)[0]


def dodge_corpus(seed):
    """The quagmire dodge: one zero offset in a five-step schedule."""
    rng = random.Random(seed)
    K = rng.sample(range(M), M)
    return encipher(
        plaintext(),
        rng.sample(range(M), M),
        alphabets(K, schedule(rng, zeros=1)),
        rng.sample(range(M), M),
    )


def preventer_corpus(seed, phi=0.90):
    """The rival: an order-5 walk whose preventer fires with probability phi."""
    rng = random.Random(seed)
    g = order5(rng)
    powers = [power(g, k) for k in range(5)]
    sigma = rng.sample(range(M), M)
    base = rng.sample(range(M), M)
    out, clock, previous = [], 0, None
    for word in plaintext():
        emitted = []
        for p in word:
            c = base[powers[clock % 5][p]]
            if c == previous and rng.random() < phi:
                clock += 1
                c = base[powers[clock % 5][p]]
            emitted.append(c)
            previous = c
            clock += 1
        out.append(emitted)
        base = compose(base, compose(powers[(clock - 1) % 5], sigma))
    return out


def doublet_positions(blocks):
    """Absolute rune index of every within-block adjacent doublet."""
    out, k = [], 0
    for word in blocks:
        for j in range(len(word)):
            if j and word[j] == word[j - 1]:
                out.append(k)
            k += 1
    return out


def aligned_profile(blocks, limit):
    """Gap residues mod 5, rotated so this corpus's own modal residue comes first."""
    positions = doublet_positions(blocks)
    counts = np.zeros(5)
    for a, b in zip(positions, positions[1:]):
        if b - a <= limit:
            counts[(b - a) % 5] += 1
    if not counts.sum():
        return counts
    return np.roll(counts, -int(np.argmax(counts)))


def reference(generator, limit):
    total = np.zeros(5)
    for s in REFERENCE_SEEDS:
        total += aligned_profile(generator(s), limit)
    return total / total.sum()


def log_ratio(counts, favour, against):
    def ll(p):
        p = np.maximum(p, 1e-3)
        return float(np.sum(counts * np.log(p / p.sum())))

    return ll(favour) - ll(against)


def main() -> None:
    body = [b for b, _ in body_blocks(set())]

    print("First: does the dodge model pass the test that refuted phase-gating?")
    print("That test asks whether doublets pile up at one ABSOLUTE position mod 5.")
    print(
        "The right question is whether the corpus's value is unusual under the model.\n"
    )

    def position_chi2(blocks):
        positions = doublet_positions(blocks)
        counts = np.bincount([p % 5 for p in positions], minlength=5).astype(float)
        expected = counts.sum() / 5
        return (
            float(((counts - expected) ** 2 / expected).sum()),
            counts,
            len(positions),
        )

    body_chi, body_counts, body_n = position_chi2(body)
    model = [position_chi2(dodge_corpus(s)) for s in range(40)]
    model_chi = np.array([m[0] for m in model])
    print(f"{'corpus':<34}{'doublets':>9}{'counts mod 5':>24}{'chi2(4)':>9}")
    print(
        f"{'the body':<34}{body_n:>9}"
        f"{str([int(x) for x in body_counts]):>24}{body_chi:>9.2f}"
    )
    print(
        f"{'quagmire-dodge, 40 seeds':<34}{int(np.mean([m[2] for m in model])):>9}"
        f"{'':>24}{f'{model_chi.mean():.2f} +- {model_chi.std(ddof=1):.2f}':>9}"
    )
    print(
        f"\nP(chi2 >= the body's | the dodge model) = "
        f"{float((model_chi >= body_chi).mean()):.2f}"
    )
    print(
        "\nThe corpus's value is an ordinary draw from the model it was used to reject,"
        "\nso the recorded refutation establishes nothing either way: every dodge shifts"
        "\nthe clock off absolute position, about one step per 34 runes.\n"
    )

    print(
        "Second: the gap between consecutive doublets, which the drift does not erase.\n"
    )
    print(
        f"{'gap limit':<11}{'body gaps':>10}{'body log LR':>13}"
        f"{'P(>=obs|dodge)':>16}{'P(<=obs|prev)':>15}{'dodge acc':>11}{'prev acc':>10}"
    )
    for limit in GAP_LIMITS:
        prof_dodge = reference(dodge_corpus, limit)
        prof_prev = reference(preventer_corpus, limit)
        observed = log_ratio(aligned_profile(body, limit), prof_prev, prof_dodge)
        from_dodge = np.array(
            [
                log_ratio(
                    aligned_profile(dodge_corpus(s), limit), prof_prev, prof_dodge
                )
                for s in range(TRIALS)
            ]
        )
        from_prev = np.array(
            [
                log_ratio(
                    aligned_profile(preventer_corpus(s), limit), prof_prev, prof_dodge
                )
                for s in range(TRIALS)
            ]
        )
        n_gaps = int(aligned_profile(body, limit).sum())
        print(
            f"{limit:<11}{n_gaps:>10}{observed:>13.2f}"
            f"{float((from_dodge >= observed).mean()):>16.3f}"
            f"{float((from_prev <= observed).mean()):>15.3f}"
            f"{float((from_dodge < 0).mean()):>11.0%}{float((from_prev > 0).mean()):>10.0%}"
        )

    limit = 40
    prof_dodge, prof_prev = (
        reference(dodge_corpus, limit),
        reference(preventer_corpus, limit),
    )
    print(f"\naligned profiles at a {limit}-rune limit:")
    print(f"  quagmire-dodge   {np.round(prof_dodge, 3)}")
    print(f"  preventer        {np.round(prof_prev, 3)}")
    counts = aligned_profile(body, limit)
    print(
        f"  the body         {np.round(counts / counts.sum(), 3)}   ({int(counts.sum())} gaps)"
    )
    print(
        f"\nlikelihood ratio for the preventer at this limit: "
        f"{math.exp(log_ratio(counts, prof_prev, prof_dodge)):.0f} : 1"
    )

    print(
        "\nThe body favours the preventer at every limit tried, and the evidence is"
        "\nstrongest for short gaps, which is where the signature should live: a 90-rune"
        "\nlimit admits enough intervening dodges to wash the residue out, and there the"
        "\nlog ratio falls to +0.70. So 40 runes is not a cherry-picked threshold, but the"
        "\nresult does depend on staying inside the range where the drift is small."
        "\nIt rests on few gaps, and the simulations use prose rather than the LP's own"
        "\nregister -- the signature is clock mechanics rather than plaintext, but that"
        "\nis an argument, not a measurement."
    )


if __name__ == "__main__":
    main()
